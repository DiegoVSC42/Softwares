# Pontuacao que gruda na palavra e nao faz parte dela. A apostrofe fica de
# fora de proposito: em "D'Oeste" ela e parte do nome.
SINAIS = ".,;:()[]{}!?\""


def _palavra(p, primeira):
    """Formata uma palavra: sigla fica, acento entra, resto vira Titulo."""
    limpa = p.strip(SINAIS)
    if limpa.upper() in INTOCAVEIS:
        return p
    if limpa.upper() in ACENTOS:
        certa = ACENTOS[limpa.upper()]
        return p.replace(limpa, certa) if limpa != p else certa
    baixa = p.lower()
    if not primeira and baixa in MINUSCULAS:
        return baixa
    # Mantem o que ja veio acentuado (o TSE acentua os nomes de urna).
    partes = []
    for pedaco in baixa.replace("-", " - ").split(" "):
        # Sobe a primeira LETRA, e nao o primeiro caractere: senao uma palavra
        # que comeca com parentese sairia inteira em minuscula, porque "("
        # ja e igual ao seu proprio maiusculo.
        for i, ch in enumerate(pedaco):
            if ch.isalpha():
                pedaco = pedaco[:i] + ch.upper() + pedaco[i + 1:]
                break
        partes.append(pedaco)
    return " ".join(partes).replace(" - ", "-")


def formatar(nome):
    """MAIUSCULAS DO CADASTRO -> Letra de Forma Legivel."""
    palavras = nome.split()
    return " ".join(_palavra(p, i == 0) for i, p in enumerate(palavras))


