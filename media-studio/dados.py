def chave_alfabetica(texto):
    """Ordem alfabetica do portugues: acento nao muda o lugar da palavra.

    Sem isto, "Agna" cairia depois de "Zuleide", porque o computador ordena
    pelo codigo interno da letra e "A" nao e "A". Aqui o acento e removido
    so para efeito de comparacao; o nome continua sendo exibido com acento.
    """
    sem_acento = unicodedata.normalize("NFD", texto)
    sem_acento = "".join(c for c in sem_acento if not unicodedata.combining(c))
    return sem_acento.lower()


def _ordenar(lista, chave):
    return sorted(lista, key=lambda x: chave_alfabetica(chave(x)))


def candidatos(cargo):
    """Devolve [(nome_formatado, numero, partido)] em ordem alfabetica."""
    bruto = {
        "governador": GOVERNADOR,
        "senador": SENADOR,
        "federal": DEPUTADO_FEDERAL,
        "estadual": DEPUTADO_ESTADUAL,
    }[cargo]
    pronto = [(formatar(n), num, p) for (n, num, p) in bruto]
    return _ordenar(pronto, lambda x: x[0])


def hospitais():
    """Devolve [(nome_formatado, municipio)] em ordem alfabetica."""
    pronto = [(formatar(n), m) for (n, m) in HOSPITAIS]
    return _ordenar(pronto, lambda x: x[0])


def cidades():
    return sorted(CIDADES, key=chave_alfabetica)
